# 위험성향 점수 계산
# ============================================================

def calculate_risk_score(answers):
    """
    위험성향 문항만 이용해서 risk_score를 계산한다.

    각 문항은 1~5점
    위험성향 문항은 총 15개

    평균을 1~5 범위로 구한 뒤
    3을 곱해서 3~15 범위의 risk_score로 변환한다.
    """

    total = sum(answers)

    average = total / len(answers)

    risk_score = round(average * 3)

    return risk_score


# ============================================================
# 투자성향 결정
# ============================================================

def get_investment_type(risk_score):
    """
    risk_score에 따라 투자성향 결정
    """

    if risk_score <= 7:
        return "안정형"

    elif risk_score <= 10:
        return "균형형"

    else:
        return "공격형"


