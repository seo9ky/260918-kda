# ============================================================
# 공통 응답
# ============================================================

def get_answer(question):
    while True:
        print(f"\n{question}")
        print("1. 전혀 그렇지 않다")
        print("2. 그렇지 않은 편이다")
        print("3. 보통이다")
        print("4. 그런 편이다")
        print("5. 매우 그렇다")

        answer = input("선택: ")

        if answer in ["1", "2", "3", "4", "5"]:
            return int(answer)

        print("1~5 중에서 선택해주세요.")


# ============================================================
# 위험성향 점수 계산
# ============================================================

def calculate_risk_score(answers):
    """
    위험성향 문항만 이용해서 risk_score를 계산한다.

    각 문항은 1~5점
    위험성향 문항은 총 15개

    평균을 1~5 범위로 구한 뒤
    3을 곱해서 3~15 범위의 risk_score로 변환한다.
    """

    total = sum(answers)

    average = total / len(answers)

    risk_score = round(average * 3)

    return risk_score


# ============================================================
# 투자성향 결정
# ============================================================

def get_investment_type(risk_score):
    """
    risk_score에 따라 투자성향 결정
    """

    if risk_score <= 7:
        return "안정형"

    elif risk_score <= 10:
        return "균형형"

    else:
        return "공격형"


# ============================================================
# 손실 감내 수준
# ============================================================

def get_loss_tolerance(investment_type):
    """
    투자성향에 따른 손실 감내 수준
    """

    if investment_type == "안정형":
        return "낮음"

    elif investment_type == "균형형":
        return "중간"

    else:
        return "높음"


# ============================================================
# 목표 수익률
# ============================================================

def get_target_return(investment_type):
    """
    투자성향에 따른 목표 수익률
    """

    if investment_type == "안정형":
        return 5.0

    elif investment_type == "균형형":
        return 8.0

    else:
        return 12.0


# ============================================================
# 투자기간
# ============================================================

def get_investment_period():
    """
    투자기간은 위험성향 점수와 별개로 직접 선택한다.
    """

    while True:
        print("\n========================")
        print("       투자 기간")
        print("========================")

        print("1. 1년 미만")
        print("2. 1~3년")
        print("3. 3~5년")
        print("4. 5~10년")
        print("5. 10년 이상")

        answer = input("선택: ")

        periods = {
            "1": "단기",
            "2": "중기",
            "3": "중기",
            "4": "장기",
            "5": "장기"
        }

        if answer in periods:
            return periods[answer]

        print("1~5 중에서 선택해주세요.")


# ============================================================
# 전체 투자성향 계산
# ============================================================

def get_investment_result():

    # --------------------------------------------------------
    # 1. 위험성향 설문
    # --------------------------------------------------------

    answers = []

    for i, question in enumerate(RISK_QUESTIONS, start=1):
        print(f"\n===== 위험성향 {i}/{len(RISK_QUESTIONS)} =====")

        answer = get_answer(question)

        answers.append(answer)

    # --------------------------------------------------------
    # 2. 위험성향 점수 계산
    # --------------------------------------------------------

    risk_score = calculate_risk_score(answers)

    # --------------------------------------------------------
    # 3. 투자성향 결정
    # --------------------------------------------------------

    investment_type = get_investment_type(risk_score)

    # --------------------------------------------------------
    # 4. 손실 감내 수준
    # --------------------------------------------------------

    loss_tolerance = get_loss_tolerance(investment_type)

    # --------------------------------------------------------
    # 5. 목표 수익률
    # --------------------------------------------------------

    target_return = get_target_return(investment_type)

    # --------------------------------------------------------
    # 6. 투자기간
    # --------------------------------------------------------

    investment_period = get_investment_period()

    # --------------------------------------------------------
    # 7. 최종 결과
    # --------------------------------------------------------

    return {
        "risk_score": risk_score,
        "investment_type": investment_type,
        "investment_period": investment_period,
        "loss_tolerance": loss_tolerance,
        "target_return": target_return
    }


# ============================================================
# 단독 실행 테스트
# ============================================================

if __name__ == "__main__":

    result = get_investment_result()

    print("\n========================")
    print("       투자성향 결과")
    print("========================")

    print(f"위험 점수 : {result['risk_score']}")
    print(f"투자 성향 : {result['investment_type']}")
    print(f"투자 기간 : {result['investment_period']}")
    print(f"손실 감내 : {result['loss_tolerance']}")
    print(f"목표 수익률 : {result['target_return']}%")

