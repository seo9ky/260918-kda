def get_answer(question):
    while True:
        print(f"\n{question}")
        print("1. 전혀 그렇지 않다")
        print("2. 그렇지 않은 편이다")
        print("3. 보통이다")
        print("4. 그런 편이다")
        print("5. 매우 그렇다")

        answer = input("선택: ")

        if answer in ["1", "2", "3", "4", "5"]:
            return int(answer)

        print("1~5 중에서 선택해주세요.")


